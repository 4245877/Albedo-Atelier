import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, before, test } from "node:test";

import Fastify, { type FastifyError, type FastifyInstance } from "fastify";

/*
 * The history / reprint / batch HTTP surface over the real farmStore singleton:
 * the wiring, the request shapes, the status codes and the token guard. The
 * behaviour itself is pinned in `app/printQueue/history.test.ts` and
 * `app/slicing/sliceBatch.test.ts`; this proves a browser reaches it.
 *
 * env freezes on first import, so process.env is set at module top and
 * everything that reads it is imported dynamically after. No printers: the
 * reprinted job is queued, never started.
 */
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), "atelier-history-routes-"));
const TOKEN = "history-test-token";
process.env.ORCHESTRATOR_API_TOKEN = TOKEN;
process.env.STATE_FILE_PATH = path.join(TMP, "state.json");
process.env.UPLOAD_MIN_FREE_DISK_BYTES = "1048576";
process.env.PRINTERS_CONFIG_PATH = path.join(TMP, "no-printers.json");

let app: FastifyInstance;
let farmStore: typeof import("../../app/farmStore").farmStore;

before(async () => {
  const { AppError, toClientError } = await import("../../core/errors");
  const { registerSecurity } = await import("../../http/security");
  const { registerPrintQueueRoutes } = await import("./routes");
  ({ farmStore } = await import("../../app/farmStore"));

  app = Fastify();
  registerSecurity(app);
  app.setErrorHandler((error: FastifyError, _request, reply) => {
    if (error instanceof AppError) {
      reply.code(error.statusCode).send({ error: toClientError(error) });
      return;
    }
    const status = typeof error.statusCode === "number" ? error.statusCode : 500;
    reply.code(status).send({ error: { code: "ERR", message: error.message } });
  });
  await app.register(registerPrintQueueRoutes, {
    prefix: "/api/print",
    services: farmStore,
    commands: farmStore.commands
  });
  await app.ready();
});

after(async () => {
  await app.close();
  fs.rmSync(TMP, { recursive: true, force: true });
});

const AUTH = { authorization: `Bearer ${TOKEN}` };

function multipart(filename: string, data: Buffer): { payload: Buffer; headers: Record<string, string> } {
  const boundary = `----atelier${Math.random().toString(16).slice(2)}`;
  const head = Buffer.from(
    `--${boundary}\r\n` +
      `Content-Disposition: form-data; name="file"; filename="${filename}"\r\n` +
      `Content-Type: application/octet-stream\r\n\r\n`
  );
  const tail = Buffer.from(`\r\n--${boundary}--\r\n`);
  return {
    payload: Buffer.concat([head, data, tail]),
    headers: { "content-type": `multipart/form-data; boundary=${boundary}` }
  };
}

const GCODE = Buffer.from(
  ["; generated by PrusaSlicer 2.7.1", "; printer_model = MK4", "; filament_type = PLA", "G21", "G90", "G1 X0 Y0", "G1 X30 Y20"].join("\n")
);

/** Upload a G-code, queue it, cancel it — a finished (cancelled) print in history. */
let uploads = 0;
async function cancelledPrint(): Promise<string> {
  // Distinct bytes per call: identical content would be deduplicated (200, not 201).
  uploads += 1;
  const { payload, headers } = multipart("part.gcode", Buffer.concat([GCODE, Buffer.from(`\n; copy ${uploads}`)]));
  const up = await app.inject({ method: "POST", url: "/api/print/artifacts", payload, headers: { ...headers, ...AUTH } });
  assert.equal(up.statusCode, 201);
  await farmStore.artifacts.whenIdle();
  const taskId = up.json().task.id as string;
  const queued = await app.inject({ method: "POST", url: `/api/print/tasks/${taskId}/enqueue`, payload: {}, headers: AUTH });
  assert.equal(queued.statusCode, 200, queued.body);
  const cancelled = await app.inject({
    method: "POST",
    url: `/api/print/tasks/${taskId}/cancel`,
    payload: { reason: "передумали" },
    headers: AUTH
  });
  assert.equal(cancelled.statusCode, 200);
  return taskId;
}

test("GET /history lists a finished print with what can be done again", async () => {
  const taskId = await cancelledPrint();
  const res = await app.inject({ method: "GET", url: "/api/print/history?state=CANCELLED&limit=10" });
  assert.equal(res.statusCode, 200);
  const entry = res.json().entries.find((e: { taskId: string }) => e.taskId === taskId);
  assert.ok(entry);
  assert.equal(entry.state, "CANCELLED");
  assert.equal(entry.actions.reprint.allowed, true);
  assert.equal(entry.actions.reprint.route, "executable");

  const one = await app.inject({ method: "GET", url: `/api/print/history/${taskId}` });
  assert.equal(one.statusCode, 200);
  assert.equal(one.json().entry.taskId, taskId);
});

test("GET /history refuses a state that is not a finished one, and a broken cursor", async () => {
  assert.equal((await app.inject({ method: "GET", url: "/api/print/history?state=QUEUED" })).statusCode, 400);
  assert.equal((await app.inject({ method: "GET", url: "/api/print/history?cursor=nope" })).statusCode, 400);
});

test("POST /tasks/:id/reprint queues a new print, is retry-safe, and needs the token", async () => {
  const taskId = await cancelledPrint();

  const noToken = await app.inject({ method: "POST", url: `/api/print/tasks/${taskId}/reprint`, payload: {} });
  assert.equal(noToken.statusCode, 401);

  const res = await app.inject({
    method: "POST",
    url: `/api/print/tasks/${taskId}/reprint`,
    payload: { requestId: "click-1" },
    headers: AUTH
  });
  assert.equal(res.statusCode, 200, res.body);
  const body = res.json();
  assert.equal(body.ok, true);
  assert.equal(body.route, "executable");
  assert.equal(body.deduplicated, false);
  assert.equal(body.task.task.state, "QUEUED");
  assert.equal(body.task.task.metadata.reprintOf, taskId);

  const again = await app.inject({
    method: "POST",
    url: `/api/print/tasks/${taskId}/reprint`,
    payload: { requestId: "click-1" },
    headers: AUTH
  });
  assert.equal(again.json().deduplicated, true);
  assert.equal(again.json().task.task.id, body.task.task.id);

  // The new print is in the queue, not history: repeating IT is refused (409)
  // with a stable code the dashboard can branch on.
  const notYet = await app.inject({
    method: "POST",
    url: `/api/print/tasks/${body.task.task.id}/reprint`,
    payload: {},
    headers: AUTH
  });
  assert.equal(notYet.statusCode, 409);
  assert.equal(notYet.json().error.details.code, "not_finished");
});

test("batch endpoints shape their input before anything runs", async () => {
  const empty = await app.inject({
    method: "POST",
    url: "/api/print/slicing/batches",
    payload: { artifactIds: [], profileSetId: "pset_x" },
    headers: AUTH
  });
  assert.equal(empty.statusCode, 400);
  const notList = await app.inject({
    method: "POST",
    url: "/api/print/slicing/batches",
    payload: { artifactIds: "art_1", profileSetId: "pset_x" },
    headers: AUTH
  });
  assert.equal(notList.statusCode, 400);
  const unknownSet = await app.inject({
    method: "POST",
    url: "/api/print/slicing/batches",
    payload: { artifactIds: ["art_1"], profileSetId: "pset_missing" },
    headers: AUTH
  });
  assert.equal(unknownSet.statusCode, 404);

  const promote = await app.inject({
    method: "POST",
    url: "/api/print/slicing/batches/promote",
    payload: { variantIds: ["slc_missing"] },
    headers: AUTH
  });
  assert.equal(promote.statusCode, 200, "per-variant refusals are rows, not a failed request");
  assert.deepEqual(
    promote.json().items.map((i: { ok: boolean; code: string }) => [i.ok, i.code]),
    [[false, "NOT_FOUND"]]
  );
});

test("POST /slicing/variants/:id/reprint answers 404 for an unknown variant", async () => {
  const res = await app.inject({
    method: "POST",
    url: "/api/print/slicing/variants/slc_missing/reprint",
    payload: {},
    headers: AUTH
  });
  assert.equal(res.statusCode, 404);
});
